export type IssueStatus = "unresolved" | "resolved" | "ignored";

export type Platform = "browser" | "node";

export interface StackFrame {
  filename: string;
  function?: string;
  lineno?: number;
  colno?: number;
  /** Original source lines around the error, filled in by the worker from a source map. */
  context?: { pre: string[]; line: string; post: string[] };
  /** Where this frame was in the minified file, kept when a source map rewrote it. */
  minified?: { filename: string; lineno?: number; colno?: number };
}

export type BreadcrumbType = "click" | "navigation" | "fetch" | "console" | "custom";
export type BreadcrumbLevel = "debug" | "info" | "warning" | "error";

/** Something that happened before an error: a click, a request, a log line. */
export interface Breadcrumb {
  type: BreadcrumbType;
  /** ISO 8601 client time. */
  timestamp: string;
  message: string;
  level?: BreadcrumbLevel;
  data?: Record<string, string | number | boolean | null>;
}

/** A single error occurrence as sent by the SDK. This is the wire format of the ingestion API. */
export interface ErrorEvent {
  /** UUID generated by the SDK. Resending the same event is safe: the server stores it once. */
  eventId: string;
  /** ISO 8601 time the error happened on the client. */
  timestamp: string;
  platform: Platform;
  /** Error class name, e.g. `TypeError`. */
  type: string;
  message: string;
  /** Raw `error.stack`, kept for debugging and future re-parsing. */
  stack?: string;
  /** Parsed stack, innermost frame first. */
  frames: StackFrame[];
  url?: string;
  userAgent?: string;
  release?: string;
  environment?: string;
  /** Oldest first, at most 100. */
  breadcrumbs?: Breadcrumb[];
}

/** BullMQ queue the API writes accepted events to. */
export const EVENTS_QUEUE = "events";
/** Events whose processing failed on every attempt, kept for inspection and replay. */
export const EVENTS_DEAD_LETTER_QUEUE = "events-dead-letter";

export interface IngestJobData {
  projectId: string;
  event: ErrorEvent;
  /** ISO time the API accepted the event. Issue first/last seen use this, not the client clock. */
  receivedAt: string;
}

export interface DeadLetterJobData extends IngestJobData {
  failedReason: string;
  attemptsMade: number;
}

/** BullMQ queue for outgoing notifications, separate so a slow webhook never delays grouping. */
export const ALERTS_QUEUE = "alerts";

export type AlertKind = "new_issue" | "regression";

export interface AlertJobData {
  kind: AlertKind;
  projectId: string;
  issueId: string;
  /** The event that triggered the alert. */
  eventId: string;
}

// Dashboard API response shapes. Dates are ISO 8601 strings.

export interface UserDto {
  id: string;
  email: string;
  name: string | null;
}

export interface ProjectDto {
  id: string;
  name: string;
  /** Public key the SDK sends with every event. */
  apiKey: string;
  dsn: string;
  alertWebhookUrl: string | null;
  /** Whether a source map upload token exists. The token itself is only shown once. */
  hasUploadToken: boolean;
  createdAt: string;
}

export interface SourceMapReleaseDto {
  release: string;
  files: number;
  bytes: number;
  lastUploadAt: string;
}

/** A group of events that share the same fingerprint. */
export interface IssueDto {
  id: string;
  type: string;
  message: string;
  culprit: string | null;
  status: IssueStatus;
  count: number;
  firstSeen: string;
  lastSeen: string;
}

export interface IssueListResponse {
  issues: IssueDto[];
  total: number;
  page: number;
  limit: number;
}

export interface EventDto {
  id: string;
  eventId: string;
  platform: Platform;
  type: string;
  message: string;
  stack: string | null;
  frames: StackFrame[];
  url: string | null;
  userAgent: string | null;
  release: string | null;
  environment: string | null;
  breadcrumbs: Breadcrumb[];
  /** Client time. */
  timestamp: string;
  /** Server time; issue first/last seen are based on this. */
  receivedAt: string;
}

export interface IssueDetailResponse {
  issue: IssueDto;
  latestEvent: EventDto | null;
}

export type StatsRange = "24h" | "7d";

export interface IssueStatsResponse {
  range: StatsRange;
  /** One bucket per hour (24h) or day (7d), oldest first, including empty ones. */
  buckets: { start: string; count: number }[];
}
